export function setLanguage(lang) {
    const selectedLang = translations[lang] ? lang : "fr";
    const dictionary = translations[selectedLang];
    
    localStorage.setItem("arashi_lang", selectedLang);

    // Prise en charge du sens de lecture RTL pour l'arabe
    if (selectedLang === "ar") {
        document.documentElement.dir = "rtl";
        document.documentElement.lang = "ar";
    } else {
        document.documentElement.dir = "ltr";
        document.documentElement.lang = selectedLang;
    }

    // Remplacement dynamique du texte pour toutes les balises équipées de data-lang
    document.querySelectorAll("[data-lang]").forEach(element => {
        const key = element.getAttribute("data-lang");
        if (dictionary[key]) {
            if (element.tagName === "INPUT" && element.hasAttribute("placeholder")) {
                element.placeholder = dictionary[key];
            } else {
                element.textContent = dictionary[key];
            }
        }
    });

    // Synchronisation des sélecteurs de langue
    document.querySelectorAll("#sidebarLanguageSelect, #footerLanguageSelect").forEach(select => {
        select.value = selectedLang;
    });
}

window.changeLanguage = function(lang) {
    setLanguage(lang);
};

document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("arashi_lang") || "fr";
    setLanguage(savedLang);
});